/**
 * Extracts Lucide icon geometry into plain SVG strings for Leaflet divIcons,
 * so map markers share the UI icon set without rendering React inside Leaflet.
 *
 *   node scripts/generate-marker-icons.mjs
 */
import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ICONS = {
  sos: "siren",
  shelter: "house",
  hospital: "hospital",
  team: "life-buoy",
  flooded_road: "waves-horizontal",
  landslide: "mountain",
  blocked_bridge: "construction",
  waterlogging: "droplets",
  damaged_infrastructure: "zap",
  stranded_people: "users",
  other: "circle-alert",
  warning: "triangle-alert",
};

const out = {};
for (const [key, name] of Object.entries(ICONS)) {
  const mod = await import(resolve(root, `node_modules/lucide-react/dist/esm/icons/${name}.mjs`));
  const node = mod.__iconData.node;
  out[key] = node
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs)
        .filter(([k]) => k !== "key")
        .map(([k, v]) => `${k}="${v}"`)
        .join(" ");
      return `<${tag} ${a}/>`;
    })
    .join("");
}

const file = `// GENERATED by scripts/generate-marker-icons.mjs — do not edit.
// Icon geometry from Lucide (https://lucide.dev), ISC License.
export const MARKER_ICON_PATHS = ${JSON.stringify(out, null, 2)} as const;

export type MarkerIconKey = keyof typeof MARKER_ICON_PATHS;
`;
writeFileSync(resolve(root, "components/map/marker-icon-paths.ts"), file);
console.log(`Wrote ${Object.keys(out).length} marker icons`);
